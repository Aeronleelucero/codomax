// Optional browser verification. Install playwright-core and a Chromium browser,
// or set PLAYWRIGHT_MODULE and CHROMIUM_PATH to existing installations.
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { createServer } from 'vite';
import { startFixture } from '../backend/tests/support/fixture.js';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const fixture = await startFixture();
const { env } = await import('../backend/src/config/env.js');
let vite, browser;
const password = `Browser1-${randomBytes(12).toString('hex')}`;
const email = `browser-${randomBytes(8).toString('hex')}@example.com`;
let checks = 0;
function passed(description) { checks += 1; console.log(`PASS ${description}`); }
try {
  vite = await createServer({ server: { host: '127.0.0.1', port: 0,
    proxy: { '/api': { target: fixture.base.replace(/\/api$/, ''), changeOrigin: true } } } });
  await vite.listen();
  const origin = `http://127.0.0.1:${vite.httpServer.address().port}`;
  env.frontendUrls.push(origin);
  browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH && { executablePath: process.env.CHROMIUM_PATH }) });
  const context = await browser.newContext();
  const page = await context.newPage();
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));
  await page.goto(`${origin}/dashboard/blogs`);
  await page.waitForURL('**/login');
  await page.getByRole('heading', { name: 'Welcome back' }).waitFor();
  passed('unauthenticated dashboard redirects to login');
  await page.locator('#main-content').getByRole('link', { name: 'Create an account' }).click();
  await page.getByLabel('Full name').fill('Browser Writer');
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByLabel('Confirm password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.waitForURL('**/login');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.waitForURL('**/dashboard/blogs');
  await page.getByRole('heading', { name: 'My Blogs', exact: true }).waitFor();
  passed('registration and login preserve intended destination');
  assert.equal(await page.evaluate(() => localStorage.getItem('artikly.auth')), null);
  assert.equal(await page.evaluate(() => document.cookie.includes('artikly-session')), false);
  passed('authentication is absent from localStorage and document.cookie');
  await page.reload();
  await page.getByRole('heading', { name: 'My Blogs', exact: true }).waitFor();
  passed('refresh restores the authenticated dashboard');
  await page.getByRole('link', { name: 'Write an Article', exact: true }).first().click();
  await page.getByLabel('Title', { exact: false }).fill('Browser private draft');
  await page.getByRole('button', { name: 'Save as draft', exact: false }).click();
  await page.waitForURL('**/dashboard');
  await page.getByRole('link', { name: 'Browser private draft', exact: true }).waitFor();
  passed('dashboard creates and displays an owned draft');
  await page.getByRole('link', { name: 'Profile settings', exact: true }).click();
  await page.getByLabel('Full name', { exact: true }).fill('Updated Browser Writer');
  await page.getByRole('button', { name: 'Save profile', exact: true }).click();
  await page.getByText('Your profile has been updated.', { exact: true }).waitFor();
  passed('profile form saves changes');
  await page.setViewportSize({ width: 375, height: 812 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: '/tmp/artikly-profile-mobile.png', fullPage: true });
  passed('profile remains responsive at 375px');
  await page.setViewportSize({ width: 1280, height: 900 });
  const second = await context.newPage();
  await second.goto(`${origin}/dashboard`);
  await second.getByRole('heading', { name: 'Welcome back, Updated', exact: false }).waitFor();
  await page.getByRole('button', { name: 'Log out', exact: true }).last().click();
  await page.waitForURL('**/login');
  await second.waitForURL('**/login');
  passed('logout clears protected content in both tabs');
  await page.goBack();
  await page.waitForURL('**/login');
  assert.equal(await page.getByText('Browser private draft', { exact: true }).count(), 0);
  passed('back navigation after logout does not reveal private content');
  await page.getByLabel('Email address', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.waitForURL(/\/dashboard/);
  await page.goto(`${origin}/dashboard/profile`);
  await page.getByLabel('Current password', { exact: true }).fill(password);
  const next = `NewBrowser1-${randomBytes(12).toString('hex')}`;
  await page.getByLabel('New password', { exact: true }).fill(next);
  await page.getByLabel('Confirm new password', { exact: true }).fill(next);
  await page.getByRole('button', { name: 'Change password', exact: true }).click();
  await page.waitForURL('**/login');
  await page.getByLabel('Email address', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(next);
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.waitForURL(/\/dashboard/);
  passed('password change requires reauthentication and new password works');
  assert.deepEqual(pageErrors, []);
  passed('no browser runtime errors');
  console.log(`${checks} browser checks passed. Database: ${process.env.TEST_DATABASE_URL ? 'isolated PostgreSQL schema' : 'in-memory test double'}.`);
} finally {
  await browser?.close();
  await vite?.close();
  await fixture.close();
}
